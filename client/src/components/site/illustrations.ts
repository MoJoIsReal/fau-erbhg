/**
 * The illustration library.
 *
 * Six commissioned originals, one per page, each drawn a second time as the
 * same place after nightfall. They live in `attached_assets/illustrations/`
 * as ~2.4MB PNGs; what ships is the webp/jpg pair derived from each here,
 * because `client/public/` is copied verbatim into the deploy and 14MB of
 * unresized PNG would have been served to phones. Regenerate with the crop
 * rectangles below if an original is ever replaced.
 *
 * **Two crops per scene, not one crop stretched.** A hero band is a 3:1 ribbon
 * on a laptop and something close to 4:3 on a phone, and one rectangle cannot
 * be both: `object-fit: cover` would simply eat the sides on the phone and
 * take the noticeboard, the postbox or a child with it. So every illustration
 * is cut twice — a `wide` rectangle for the desktop band or column, and a
 * `narrow` one composed for the phone around whatever that page's picture is
 * actually about. `Artwork` picks between them with a `media` query, so only
 * one is ever fetched, and the narrow frame then renders at its own ratio: on
 * a phone nothing is cropped at all, because the crop already happened here.
 * `focus` is the `object-position` for the frames in between — it names what
 * must survive, rather than defaulting to the centre.
 *
 * **Dark mode is a different drawing, not a filter.** Each night scene is
 * served in place of its daylight sibling, never over it: no grayscale, no
 * dimming, no overlay — warm lamps, twilight, fjord lights. Where the night
 * scene was drawn to the same geometry the crop rectangle is shared, and
 * where it is a different composition (Kontakt and Dokumenter, both redrawn
 * rather than repainted) it gets its own rectangle at the *same ratio*, so
 * the page keeps one shape in both themes.
 *
 * Two rules govern every crop:
 *
 * 1. **The values are the official ones.** Wherever a signpost appears it
 *    reads FOR BARNA / SAMMEN / ENGASJEMENT, complete — never two of the
 *    three. This is what holds the Dokumenter crop at its full height and
 *    what fixes the right edge of both home rectangles.
 * 2. **A crop may keep the artwork's own handwritten aside; it may never
 *    keep lettering that repeats the page's own heading, or a line the page
 *    already prints as HTML.** So both home crops clear "Velkommen til FAU
 *    Erdal Barnehage" (the page's h1), Aktuelt starts below the noticeboard's
 *    "AKTUELT" plank (the same), and Kalender starts below "Små mennesker,
 *    store dager" because the calendar hero prints that tagline itself.
 *    Dokumenter keeps "Nyttig og oversiktlig" and Kontakt keeps "Ta gjerne
 *    kontakt": neither sentence exists anywhere else on its page, so nothing
 *    is being said only in pixels. A crop never cuts *through* lettering —
 *    an edge either clears a phrase completely or keeps all of it.
 */

/** One rendition: two widths, two formats, and the crop's own dimensions. */
export interface ArtSource {
  webp: string;
  jpg: string;
  srcSet: string;
  jpgSrcSet: string;
  /** Intrinsic width/height of the crop, to reserve layout space. */
  width: number;
  height: number;
}

/** Where a frame narrower than the crop should hold on, per breakpoint tier. */
export interface ArtFocus {
  /** Under 640px — only used by frames that do crop the narrow rendition. */
  narrow: string;
  /** 640–1279px: tablets, and every hero band on a laptop. */
  mid: string;
  /** 1280px and up. */
  wide: string;
}

/** One theme's pair of crops. */
export interface ArtVariant {
  wide: ArtSource;
  narrow: ArtSource;
  focus: ArtFocus;
}

export interface IllustrationSet {
  light: ArtVariant;
  dark: ArtVariant;
  /**
   * The ratios a frame takes when it follows the artwork rather than a fixed
   * height — `width / height` of each crop. Numbers, because a frame has to
   * be able to compare them (see `--art-mid` in page-hero). Shared between
   * the themes, because the night crops are cut to the same ratios.
   */
  ratio: { wide: number; narrow: number };
}

function source(
  small: string,
  large: string,
  smallJpg: string,
  largeJpg: string,
  smallWidth: number,
  largeWidth: number,
  width: number,
  height: number,
): ArtSource {
  return {
    webp: large,
    jpg: largeJpg,
    srcSet: `${small} ${smallWidth}w, ${large} ${largeWidth}w`,
    jpgSrcSet: `${smallJpg} ${smallWidth}w, ${largeJpg} ${largeWidth}w`,
    width,
    height,
  };
}

function illustration(light: ArtVariant, dark: ArtVariant): IllustrationSet {
  return {
    light,
    dark,
    ratio: {
      wide: light.wide.width / light.wide.height,
      narrow: light.narrow.width / light.narrow.height,
    },
  };
}

